export type MascotPose =
  | "NORMAL" | "SURPRESO" | "DESCONFIADO" | "BRAVO" | "RINDO" | "IRONICO" | "INDIGNADO"
  | "APONTANDO" | "APONTANDO_ESQUERDA" | "APONTANDO_DIREITA" | "APONTANDO_CIMA" | "APONTANDO_BAIXO"
  | "EXPLICANDO" | "PENSANDO" | "MAO_NA_CABECA" | "DINHEIRO" | "POSITIVO" | "NEGATIVO"
  | "FACEPALM" | "ASSUSTADO" | "DINHEIRO_DOENDO" | "SUSSURRO" | "NEGANDO" | "CONCORDANDO";

/** The host participates in the scene instead of sitting fixed in a corner:
 *  it can enter from a side, sit centered/enlarged for a reaction beat, or
 *  stay in its default reading spot — BUYER_PAIN_V2 adds foreground
 *  left/right so it can read as "in the scene", not just a corner watermark. */
export type MascotPosition = "BOTTOM_RIGHT" | "BOTTOM_LEFT" | "TOP_RIGHT" | "TOP_LEFT" | "CENTER" | "FOREGROUND_LEFT" | "FOREGROUND_RIGHT";
export type MascotEnterFrom = "LEFT" | "RIGHT" | "NONE";

export interface TimedSfx {
  type: "WHOOSH" | "POP" | "CLICK" | "IMPACT" | "RISER";
  src: string; // staticFile-relative path
  offsetSec?: number; // within the block
}

export interface VideoCut {
  src: string; // staticFile-relative path
  startFromSec?: number;
  camera?: "PUSH_IN" | "PUSH_OUT" | "STATIC";
}

export interface TimedBlock {
  id: string;
  startSec: number;
  durationSec: number;
  /** 1 entry = one shot for the whole block; 2+ = an internal hard cut so no
   *  block ever holds a single static composition for more than ~2s. */
  videoCuts: VideoCut[];
  keyword?: string;
  keywordVariant?: "NORMAL" | "BIG_NUMBER";
  keywordOffsetSec?: number;
  /** HOST_SAFE_ZONE / KINETIC_TEXT_SAFE_ZONE collision avoidance
   *  (buyer-pain-v2): computed once in code from the host's real
   *  position+size for this beat, never left to overlap by chance. */
  keywordTextPosition?: "TOP" | "CENTER" | "BOTTOM";
  mascotPose?: MascotPose;
  mascotPunchIn?: boolean;
  mascotPosition?: MascotPosition;
  mascotEnterFrom?: MascotEnterFrom;
  mascotScale?: number;
  patternInterrupt?: boolean;
  sfx?: TimedSfx;
  // P0 additions (2026-09-15): optional per-beat overrides.
  visualRegister?: VisualRegister;
  screenEvidence?: ScreenEvidenceProps;
  hookBlock?: HookBlock;
}

export interface NarratedReelV3Props {
  blocks: TimedBlock[];
  /** MAISCAR_VOICE_LOCK (format-lock v1): ONE narration file for the whole
   *  Reel, generated by a SINGLE TTS call — never per-block files, so there
   *  is structurally no possibility of a voice/config change mid-video. */
  narrationSrc: string;
  musicSrc?: string;
  fps: number;
}


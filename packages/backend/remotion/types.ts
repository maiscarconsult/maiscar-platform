/**
 * Visual register a beat occupies on screen. Used by:
 *  - the Haiku writer to distribute registers across a Reel
 *  - the QA gate REGISTER_COUNT >= 4
 *  - the POWERPOINT_STYLE detector
 *  - the renderer to route SCREEN_EVIDENCE beats to <ScreenEvidence />
 */
export type VisualRegister =
  | "PRESENTER_FACE"     // mascot reaction shot in a corner
  | "SCREEN_EVIDENCE"    // phone-frame with a plausible page inside it
  | "PRODUCT_MACRO"      // close-up of a car part, tire, dashboard, key
  | "DOCUMENT"           // contract, receipt, sticker, VIN plate
  | "LOCATION_BROLL"     // mechanic bay, dealership floor, road, gas station
  | "BIG_NUMBER"         // full-frame kinetic number (R$, %, months, years)
  | "MONEY_STACK";       // cash, cards, calculator, PIX screen

/**
 * The HOOK is a separate produced asset from the rest of the Reel. When set on
 * beat 0, the renderer forces mascot off for the first 15 frames, slams the
 * `firstOnScreenText` onto frame 1, and QA enforces HOOK_FIRST_WORD_LATENCY
 * <= 200ms plus FIRST_ON_SCREEN_TEXT presence.
 */
export interface HookBlock {
  firstOnScreenText: string;              // 3-5 words, ALL CAPS by convention
  firstShotRegister: "PRESENTER_FACE" | "SCREEN_EVIDENCE" | "PRODUCT_MACRO";
  /** Optional; the pipeline measures this from the assembled narration MP3. */
  voiceStartOffsetMs?: number;
}

/**
 * Deterministic props for a SCREEN_EVIDENCE beat. The pipeline composes these
 * from the beat's own claim + tier — never a real screenshot of a real
 * service. Rendering happens in <ScreenEvidence /> (packages/backend/remotion/ScreenEvidence.tsx).
 */
export type ScreenEvidenceTemplate =
  | "FINANCING_QUOTE"    // parcela x N | CET | R$ total
  | "LISTING_PAGE"       // marketplace card
  | "WHATSAPP_THREAD"    // seller vs. buyer chat
  | "PIX_RECEIPT"        // transfer confirmation
  | "INVOICE";           // service invoice

export interface ScreenEvidenceProps {
  template: ScreenEvidenceTemplate;
  /** Free-form key/value pairs interpolated into the template. */
  values: Record<string, string>;
  /** Optional highlight: which key(s) should pulse/underline on-screen. */
  highlight?: string[];
}

/**
 * Adds VisualRegister / HookBlock / ScreenEvidenceProps to TimedBlock as
 * OPTIONAL fields. Old callers that don't set them continue to work; new
 * callers can use them without a breaking migration.
 */
export interface TimedBlockV3Additions {
  visualRegister?: VisualRegister;
  hookBlock?: HookBlock;
  screenEvidence?: ScreenEvidenceProps;
}

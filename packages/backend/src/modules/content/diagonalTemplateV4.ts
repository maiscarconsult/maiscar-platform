// MASTER DIAGONAL — brand constants, frozen 2026-09-03 after the Visual Lock
// directive. This is now the ONLY production template (see the dispatcher at
// the bottom of the file, which refuses every other family for the feed).
// These sizes do NOT auto-scale: a title/complement that doesn't fit at the
// frozen size throws HeadlineOverflowError instead of shrinking — rewrite
// the copy, never the design system.

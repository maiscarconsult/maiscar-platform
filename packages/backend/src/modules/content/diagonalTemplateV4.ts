export interface HeroInput {
  family?: "hero";
  photoPath: string | Buffer;
  kicker: string;
  headline: string[];
  complement?: string;
  microCaption?: string;
  pageLabel?: string;
  flip?: boolean;
  photoPosition?: string;
  gradeSaturation?: number;
  /**
   * SEMANTIC_IMAGE_MATCH — required, no default. This can't be verified by
   * code (no vision model in this pipeline), so it's a deliberate attestation
   * instead of a silent assumption: the caller confirms, at the moment this
   * specific photo was chosen for this specific content, that it actually
   * depicts/relates to what the headline says — not just "a nice car photo".
   * Passing `true` without having made that check defeats the point of the
   * gate; the field exists so skipping the check requires typing `true`
   * explicitly, not benefiting from an implicit default.
   */
  semanticMatchReviewed: boolean;
  /**
   * SEMANTIC_PHOTO_MATCH — which kind of photo this is, declared explicitly
   * so the code (not just the caller's memory) can catch the exact mistake
   * this gate exists for: text that names a specific model paired with a
   * photo of a different one.
   * - EXACT_VEHICLE: the photo shows the specific model the copy is about.
   * - CONTEXTUAL: a real photo relevant to the topic but not that specific
   *   model — only valid when `namedVehicle` is NOT set (the copy must stay
   *   generic; it can't name a model this photo doesn't show).
   * - DOCUMENTARY: real contextual photo of a process/place (oficina,
   *   trânsito, concessionária, documento) rather than a vehicle at all.
   */
  photoCategory: "EXACT_VEHICLE" | "CONTEXTUAL" | "DOCUMENTARY";
  /** Set this to the specific model name when the kicker/headline names one — forces photoCategory to EXACT_VEHICLE. Leave unset for generic copy. */
  namedVehicle?: string;
}

export class SemanticPhotoMismatchError extends Error {
  constructor(namedVehicle: string, category: string) {
    super(
      `SEMANTIC_PHOTO_MATCH bloqueou a exportação: a copy nomeia "${namedVehicle}" mas a foto está marcada como "${category}", não EXACT_VEHICLE. ` +
        `Não troque a pauta silenciosamente pra caber a foto disponível — ou ache uma foto real desse modelo, ou reescreva a copy pra ficar genérica (e então marque a foto como CONTEXTUAL), ou descarte esta pauta.`,
    );
    this.name = "SemanticPhotoMismatchError";
  }
}


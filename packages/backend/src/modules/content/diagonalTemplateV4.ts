export class HeadlineOverflowError extends Error {
  constructor(line: string, available: number) {
    super(
      `Linha "${line}" não cabe na safe zone mesmo no tamanho mínimo (largura disponível ~${Math.round(available)}px). ` +
        `Reescreva a frase mais curta — o renderer não trunca nem encolhe além do piso.`,
    );
    this.name = "HeadlineOverflowError";
  }
}

/**
 * Clean Export Rule — bloqueia a exportação (não corrige silenciosamente)
 * se qualquer texto que vai pra dentro da arte contiver metadado de
 * produção (fonte de imagem, IA, watermark, path, URL) ou continuidade
 * falsa ("deslize"/"arraste"/"continue"). Fonte editorial de fato
 * ("Fonte: dados oficiais...") pertence à legenda, nunca à peça — por
 * isso a lista bane "fonte" também, sem exceção dentro da arte.
 */
export class CleanExportError extends Error {
  constructor(field: string, matched: string) {
    super(`Clean Export Rule bloqueou a exportação: campo "${field}" contém "${matched}" — isso é metadado de produção ou continuidade falsa, não pode ir para a arte. Corrija o texto (fonte vai na legenda, não na peça).`);
    this.name = "CleanExportError";
  }
}

const BANNED_TERMS = [
  "deslize", "arraste", "continue", "próximo slide", "proximo slide", "swipe",
  "pexels", "unsplash", "shutterstock", "getty", "istock", "gerado por", "ai generated",
  "generated by", "midjourney", "pollinations", "dall-e", "dalle", "stable diffusion",
  "prompt:", "foto:", "imagem:", "fonte:", "fonte da imagem", "source:", "credit:",
  "crédito:", "watermark", "placeholder",
];
const URL_OR_PATH_RE = /(https?:\/\/|www\.|[a-zA-Z]:\\|\/Users\/|\/home\/|\.(png|jpe?g|webp|gif)\b)/i;

function assertCleanExport(fields: Record<string, string | undefined>) {
  for (const [field, value] of Object.entries(fields)) {
    if (!value) continue;
    const lower = value.toLowerCase();
    for (const term of BANNED_TERMS) {
      if (lower.includes(term)) throw new CleanExportError(field, term);
    }
    const urlMatch = value.match(URL_OR_PATH_RE);
    if (urlMatch) throw new CleanExportError(field, urlMatch[0]);
  }
}

function esc(t: string) {
  return t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function fitsAtSize(line: string, fontSize: number, maxWidthPx: number, glyphFactor = BEBAS_GLYPH_FACTOR): boolean {
  return line.length * fontSize * glyphFactor <= maxWidthPx;
}

// Greedy word-wrap for free-form support text (captions, body, data labels)
// that isn't pre-broken into lines by the caller — the DATA family's
// `caption` field originally skipped this entirely and rendered as one
// unbroken line, which overflowed past the frame on anything longer than a
// few words (caught visually during QA on the ADAS post, 2026-09-03).
function wrapText(text: string, fontSize: number, maxWidthPx: number, glyphFactor = BAHN_GLYPH_FACTOR, maxLines = 2): string[] {
  const maxChars = Math.max(6, Math.floor(maxWidthPx / (fontSize * glyphFactor)));
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length > maxChars && current) {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }
  if (current) lines.push(current);
  if (lines.length > maxLines) {
    throw new HeadlineOverflowError(text, maxWidthPx);
  }
  return lines;
}

/** Resolves one text tier to a font size within [min,target] — no floor-less shrinking, no ellipsis. Throws if even `min` doesn't fit. */
function resolveTierSize(lines: string[], target: number, min: number, maxWidthPx: number, glyphFactor = BEBAS_GLYPH_FACTOR): number {
  for (const line of lines) {
    if (!fitsAtSize(line, min, maxWidthPx, glyphFactor)) {
      throw new HeadlineOverflowError(line, maxWidthPx);
    }
  }
  let size = target;
  while (size > min && lines.some((l) => !fitsAtSize(l, size, maxWidthPx, glyphFactor))) {
    size -= 2;
  }
  return Math.max(size, min);
}

async function gradedPhoto(photoPath: string | Buffer, position?: string, saturation?: number): Promise<Buffer> {
  return sharp(photoPath)
    .resize(W, H, { fit: "cover", position: position ?? "centre" })
    .modulate({ saturation: saturation ?? 0.88, brightness: 1.0 })
    .linear(1.08, -12) // fixed brand grade — same on every photo regardless of source
    .png()
    .toBuffer();
}

async function officialLogo(targetW = 168): Promise<{ buf: Buffer; w: number; h: number }> {
  const buf = await sharp(LOGO_PATH).resize({ width: targetW }).png().toBuffer();
  const meta = await sharp(buf).metadata();
  return { buf, w: targetW, h: meta.height ?? Math.round(targetW * 0.4) };
}

function cornerBrackets(): string {
  const len = 54;
  const o1 = FRAME_INSET;
  const o2 = FRAME_INSET + 8;
  const corners: Array<[number, number, number, number]> = [
    [o1, o1, 1, 1],
    [W - o1, o1, -1, 1],
    [o1, H - o1, 1, -1],
    [W - o1, H - o1, -1, -1],
  ];
  return corners
    .map(
      ([x, y, dx, dy]) => `
      <path d="M ${x} ${y + dy * len} L ${x} ${y} L ${x + dx * len} ${y}" fill="none" stroke="${MAISCAR_RED}" stroke-width="3" />
      <path d="M ${x + dx * (o2 - o1)} ${y + dy * (len - 14)} L ${x + dx * (o2 - o1)} ${y + dy * (o2 - o1)} L ${x + dx * (len - 14)} ${y + dy * (o2 - o1)}" fill="none" stroke="${MAISCAR_RED}" stroke-width="1" stroke-opacity="0.55" />
    `,
    )
    .join("\n");
}

/** Samples a region of a rendered base (photo or flat panel) and returns a legible ink/halo pair — used by folio and any text sitting on a variable background. */
async function adaptiveInk(base: Buffer, zone: { left: number; top: number; width: number; height: number }) {
  const clampedZone = {
    left: Math.max(0, Math.min(zone.left, W - 1)),
    top: Math.max(0, Math.min(zone.top, H - 1)),
    width: Math.max(1, Math.min(zone.width, W - Math.max(0, zone.left))),
    height: Math.max(1, Math.min(zone.height, H - Math.max(0, zone.top))),
  };
  const region = await sharp(base).extract(clampedZone).grayscale().stats();
  const onDark = region.channels[0].mean < 130;
  return { color: onDark ? "#FFFFFF" : "#2A2A2A", halo: onDark ? "#000000" : "#FFFFFF", onDark };
}

function folioSvg(pageLabel: string | undefined, ink: { color: string; halo: string }): string {
  if (!pageLabel) return "";
  return `<text x="${W - MARGIN_X}" y="${H - 52}" font-family="Bahnschrift SemiBold" font-weight="600" font-size="24" letter-spacing="2" fill="${ink.halo}" fill-opacity="0.85" text-anchor="end" filter="url(#wmHalo)">${esc(pageLabel)}</text>
     <text x="${W - MARGIN_X}" y="${H - 52}" font-family="Bahnschrift SemiBold" font-weight="600" font-size="24" letter-spacing="2" fill="${ink.color}" text-anchor="end">${esc(pageLabel)}</text>`;
}

function defsBlock(): string {
  return `<filter id="wmHalo" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="5"/></filter>`;
}

